// ============================================
// robots.ts
// تنظیمات ربات‌های خزنده (Crawlers) برای پلتفرم املاک ایران
// تولید پویای robots.txt برای Next.js App Router
// ============================================

import type { MetadataRoute } from 'next';

// --------------------------------------------
// ثابت‌ها
// --------------------------------------------

/** آدرس پایه سایت */
const BASE_URL = process.env.NEXT_PUBLIC_BASE_URL || 'https://example.com';

// ============================================
// تابع اصلی تولید Robots.txt
// ============================================

/**
 * تولید فایل robots.txt
 *
 * قوانین:
 * - اجازه دسترسی به همه ربات‌ها برای صفحات عمومی
 * - ممنوعیت دسترسی به:
 *   • /api/      → اندپوینت‌های API
 *   • /admin/    → پنل مدیریت
 *   • /panel/    → پنل کاربری
 *   • /auth/     → صفحات احراز هویت
 *   • /_next/    → فایل‌های داخلی Next.js
 * - آدرس نقشه سایت
 *
 * @returns شیء استاندارد robots.txt برای Next.js
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        // ----------------------------------------
        // قانون کلی: اجازه دسترسی به همه ربات‌ها
        // برای تمام مسیرها به‌جز مسیرهای استثنا شده
        // ----------------------------------------
        userAgent: '*',
        allow: '/',
        disallow: [
          '/api/',       // اندپوینت‌های API - محتوای غیر قابل مشاهده
          '/admin/',     // پنل مدیریت - اطلاعات محرمانه
          '/panel/',     // پنل کاربری - اطلاعات شخصی کاربران
          '/auth/',      // صفحات ورود و ثبت‌نام - بدون ارزش سئو
          '/_next/',     // فایل‌های سیستمی Next.js - داخلی
        ],
      },

      {
        // ----------------------------------------
        // قانون اختصاصی Googlebot
        // محدودیت‌های دقیق‌تر برای ربات گوگل
        // ----------------------------------------
        userAgent: 'Googlebot',
        allow: '/',
        disallow: [
          '/api/',
          '/admin/',
          '/panel/',
          '/auth/',
          '/_next/',
        ],
      },

      {
        // ----------------------------------------
        // قانون اختصاصی Bingbot
        // ----------------------------------------
        userAgent: 'Bingbot',
        allow: '/',
        disallow: [
          '/api/',
          '/admin/',
          '/panel/',
          '/auth/',
          '/_next/',
        ],
      },
    ],

    // ----------------------------------------
    // آدرس نقشه سایت
    // ----------------------------------------
    sitemap: `${BASE_URL}/sitemap.xml`,

    // ----------------------------------------
    // اطلاعات اضافی (اختیاری)
    // برخی ربات‌ها از این فیلدها پشتیبانی می‌کنند
    // ----------------------------------------
    host: BASE_URL,
  };
}